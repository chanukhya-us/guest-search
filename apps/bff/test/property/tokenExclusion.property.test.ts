// Feature: ihg-guest-search, Property 5: Token exclusion — For all generated guests with
// `creditCard/token` values t (random strings >= 8 chars), `JSON.stringify(service response)`
// contains neither t nor `creditCard` nor `token` (excluding the key `revealToken`, matched
// exactly).
//
// Validates: Requirements 12.13, 25.6 (design.md "Correctness Properties" P5; threat-model row
// "Card-token leakage": allowlist parsing + property P5 + log-leak test).
//
// Why this property and not the masking one: P8 / the service-masking property already cover
// phones and emails. P5 is the card-token / unknown-element guarantee: the allowlist parser
// (`ALLOW` in contract.ts) never reads `creditCard` or its `<token>` child, so neither the token
// value, the word `creditCard`, nor a bare `token` field can ever surface in the serialized
// search RESPONSE — for ANY response the upstream might send, including ones carrying extra
// unknown elements. A second assertion lifts the same guarantee to the LOGS: nothing the app logs
// while producing that response contains the card token.
//
// How the inputs are generated (smart construction, not filtering): each run builds a REAL SOAP
// `searchGuestResponse` envelope from the contract namespaces (`NS`/`PREFIX`), with 0..N guests.
// Every guest carries a random `<ns2:creditCard token="t"><ns3:token>t</ns3:token></...>` element
// the parser must ignore, plus random contact PII in the allow-listed elements. The XML is driven
// through the REAL stack — `SoapGuestSearchGateway` (over an in-memory fetch that returns the
// generated bytes) → `parseSearchGuestResponse` → `GuestSearchService` (masking + reveal) — so the
// property exercises exactly the production path, not a hand-mapped shortcut. Token values are
// built from an alphabet disjoint from `revealToken` / `rt_` so the "token" substring check can
// never false-positive on the response's own reveal-token KEY (asserted explicitly below).
//
// >= 100 runs; a fixed seed keeps it deterministic and the runtime small (XML build + parse only).
import { fc, test } from '@fast-check/vitest';
import {
  ROLES,
  createCriteriaSchema,
  defaultSchemaConfig,
  type GuestSearchQuery,
} from '@ihg-guest-search/shared';
import { describe, expect } from 'vitest';
import pino, { type DestinationStream, type Logger } from 'pino';
import { Writable } from 'node:stream';

import type { Principal } from '../../src/auth/authProvider.js';
import { baseLoggerOptions } from '../../src/observability/logger.js';
import { MemoryRevealStore } from '../../src/security/revealStore.js';
import { NS, PREFIX } from '../../src/soap/contract.js';
import { SoapGuestSearchGateway } from '../../src/soap/soapGuestSearchGateway.js';
import type { SoapFetch, SoapFetchResponse } from '../../src/soap/transport.js';
import { createSoapTransport } from '../../src/soap/transport.js';
import { CircuitBreaker } from '../../src/soap/circuitBreaker.js';
import {
  GuestSearchService,
  type CriteriaSchema,
  type SearchContext,
} from '../../src/services/guestSearchService.js';
import { mswSoapCfg } from '../helpers/msw.js';

const SESSION_SECRET = 'prop-session-secret-0123456789abcdef';
const FIXED_MS = Date.parse('2026-10-21T12:00:00.000Z');
const schema: CriteriaSchema = createCriteriaSchema(defaultSchemaConfig);

// --- XML escaping + builder ------------------------------------------------------------------

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

interface GeneratedGuest {
  enterpriseId: string;
  given: string;
  surname: string;
  phone: string;
  email: string;
  memberId: string;
  /** The random credit-card token t (>= 8 chars). Must never reach the response/logs. */
  cardToken: string;
}

/**
 * Build a REAL `searchGuestResponse` envelope from the contract namespaces, with one
 * `<creditCard>` element per guest that the allowlist parser must ignore. The element shape
 * mirrors `response-with-cc-token.xml`: a `token` attribute AND an `ns3:token` child, both
 * carrying t. Everything else uses the allow-listed identities so the guests parse normally.
 */
function buildResponseXml(guests: readonly GeneratedGuest[]): string {
  const guestXml = guests
    .map(
      (g) => `
      <ns2:initiateGuest score="88" status="A">
        <ns2:enterpriseId>${escapeXml(g.enterpriseId)}</ns2:enterpriseId>
        <ns2:name>
          <ns3:given>${escapeXml(g.given)}</ns3:given>
          <ns3:surname>${escapeXml(g.surname)}</ns3:surname>
        </ns2:name>
        <ns2:phone number="${escapeXml(g.phone)}" type="MOBILE" location="H" profileDefault="true"/>
        <ns2:email profileDefault="true">
          <ns2:address>${escapeXml(g.email)}</ns2:address>
        </ns2:email>
        <ns2:membership code="PLACEHOLDER" value="${escapeXml(g.memberId)}" status="ACTIVE"/>
        <ns2:creditCard token="${escapeXml(g.cardToken)}" type="SYNTH">
          <ns3:token>${escapeXml(g.cardToken)}</ns3:token>
          <ns3:expiry>2099-12</ns3:expiry>
        </ns2:creditCard>
      </ns2:initiateGuest>`,
    )
    .join('');

  return `<?xml version="1.0" encoding="UTF-8"?>
<soap:Envelope xmlns:soap="${NS.soap}">
  <soap:Body>
    <${PREFIX.svc}:searchGuestResponse xmlns="${NS.common}" xmlns:${PREFIX.initiate}="${NS.initiate}" xmlns:${PREFIX.complex}="${NS.complex}" xmlns:${PREFIX.svc}="${NS.svc}" xmlns:${PREFIX.basic}="${NS.basic}">
      <header>
        <transactionStatus overallStatusCode="0000" overallStatusDescription="Success" transactionSuccessful="true"/>
      </header>${guestXml}
    </${PREFIX.svc}:searchGuestResponse>
  </soap:Body>
</soap:Envelope>`;
}

// --- generators (smart construction) ---------------------------------------------------------

// Card-token alphabet: uppercase + digits + a few symbols, deliberately EXCLUDING the lowercase
// letters of `revealToken` and `rt_`, so a surviving `token` substring is unambiguously a leak
// and never the response's own `revealToken` key. Length >= 8 per the P5 wording.
const TOKEN_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ0123456789-'.split('');
const cardTokenArb = fc
  .array(fc.constantFrom(...TOKEN_ALPHABET), { minLength: 8, maxLength: 40 })
  .map((cs) => `CCTOK-${cs.join('')}`);

// Random contact PII. Phones are >= 9 digits (masking collapses them); emails use a lowercase
// local part + synthetic domain; names/ids are plausible unique markers.
const phoneArb = fc
  .array(fc.integer({ min: 0, max: 9 }), { minLength: 9, maxLength: 14 })
  .map((ds) => `+1404555${ds.join('')}`);
const emailLocalArb = fc.string({
  unit: fc.constantFrom(...'abcdefghijklmnopqrstuvwxyz0123456789'.split('')),
  minLength: 3,
  maxLength: 18,
});
const nameArb = fc.string({
  unit: fc.constantFrom(...'abcdefghijklmnopqrstuvwxyz'.split('')),
  minLength: 3,
  maxLength: 12,
});
const idArb = fc
  .array(fc.integer({ min: 0, max: 9 }), { minLength: 9, maxLength: 9 })
  .map((ds) => `9${ds.slice(1).join('')}`);

const guestArb: fc.Arbitrary<GeneratedGuest> = fc.record({
  enterpriseId: idArb,
  given: nameArb,
  surname: nameArb,
  phone: phoneArb,
  email: emailLocalArb.map((l) => `${l}@gen.example.test`),
  memberId: idArb,
  cardToken: cardTokenArb,
});

// --- service wiring --------------------------------------------------------------------------

function principal(roles: readonly string[]): Principal {
  return { id: 'dev-user', displayName: 'Dev User', roles: [...roles] };
}
function ctx(p: Principal): SearchContext {
  return { requestId: 'req-p5', principal: p, sessionId: 'sess-p5' };
}

/** A pino logger on an in-memory sink, so lines emitted during the search can be asserted. */
function captureLogger(): { logger: Logger; text(): string } {
  const chunks: string[] = [];
  const stream = new Writable({
    write(chunk: Buffer | string, _enc, cb): void {
      chunks.push(chunk.toString());
      cb();
    },
  });
  const logger = pino(
    baseLoggerOptions({ nodeEnv: 'test', log: { level: 'trace', auditLogPath: 'x' } }),
    stream as unknown as DestinationStream,
  );
  return { logger, text: (): string => chunks.join('') };
}

/**
 * Build the real SOAP gateway + service over an in-memory fetch that returns `xml` for every
 * request. This is the production path (mapper → transport → allowlist parser → service), so
 * P5 is proven against the real code, not a shortcut mapping.
 */
function makeService(xml: string, logger: Logger): { service: GuestSearchService } {
  const soapCfg = mswSoapCfg();
  const fetch: SoapFetch = () =>
    Promise.resolve({
      status: 200,
      headers: new Headers({ 'content-type': 'text/xml; charset=utf-8' }),
      body: streamOf(xml),
    } as unknown as SoapFetchResponse);
  const breaker = new CircuitBreaker(soapCfg.breaker, { now: () => FIXED_MS });
  const transport = createSoapTransport(soapCfg, { breaker, fetch });
  const gateway = new SoapGuestSearchGateway({
    cfg: soapCfg,
    transport,
    now: () => new Date(FIXED_MS),
    logger,
  });
  let counter = 0;
  const revealStore = new MemoryRevealStore({
    ttlMs: 10 * 60 * 1000,
    now: () => FIXED_MS,
    idGenerator: () => `rt_p5-${String(++counter)}`,
  });
  const service = new GuestSearchService({
    gateway,
    schema,
    revealStore,
    sessionSecret: SESSION_SECRET,
    now: () => FIXED_MS,
    logger,
  });
  return { service };
}

/** A one-shot `ReadableStream<Uint8Array>` over a UTF-8 string, for the fake fetch body. */
function streamOf(text: string): ReadableStream<Uint8Array> {
  const bytes = new TextEncoder().encode(text);
  return new ReadableStream<Uint8Array>({
    start(c) {
      c.enqueue(bytes);
      c.close();
    },
  });
}

// --- the property ----------------------------------------------------------------------------

const QUERY: GuestSearchQuery = { lastName: 'p5probe' };
const PROP_RUNS = { numRuns: 120, seed: 0x5050 } as const;

describe('Property 5 — token exclusion over random token-bearing SOAP responses', () => {
  test.prop([fc.array(guestArb, { minLength: 0, maxLength: 10 })], PROP_RUNS)(
    'the serialized search response contains neither the card token, `creditCard`, nor a bare `token` key',
    async (guests) => {
      const xml = buildResponseXml(guests);
      const capture = captureLogger();
      const { service } = makeService(xml, capture.logger);

      // REVEAL principal exercises the token-issuing path (the richer code path that also adds
      // the `revealToken` key — which the `token` check must NOT false-positive on).
      const res = await service.search(QUERY, ctx(principal([ROLES.READ, ROLES.REVEAL])));
      const serialized = JSON.stringify(res);

      // 1. The response shape is correct: one summary per generated guest.
      expect(res.results).toHaveLength(guests.length);
      expect(res.totalResults).toBe(guests.length);

      // 2. No card token t ever appears in the serialized response (allowlist parser dropped it).
      for (const g of guests) {
        expect(serialized.includes(g.cardToken), `card token leaked: ${g.cardToken}`).toBe(false);
      }

      // 3. The word `creditCard` never appears.
      expect(serialized.includes('creditCard')).toBe(false);

      // 4. The ONLY `token` substring the response may contain is the `revealToken` key; a bare
      //    `token` (the dropped creditCard child) must never appear. Strip the exact key first,
      //    then assert no `token` remains — matching the P5 wording "excluding the key
      //    `revealToken`, matched exactly".
      const withoutRevealKey = serialized.split('"revealToken"').join('""');
      expect(withoutRevealKey.toLowerCase().includes('token')).toBe(false);

      // 5. No-log guarantee: nothing the app logs while producing this response contains a token.
      const logText = capture.text();
      for (const g of guests) {
        expect(logText.includes(g.cardToken), `card token logged: ${g.cardToken}`).toBe(false);
      }
      expect(logText.includes('creditCard')).toBe(false);
    },
  );

  test.prop([fc.array(guestArb, { minLength: 1, maxLength: 8 })], PROP_RUNS)(
    'a READ-only principal gets no reveal tokens, and still no card token survives',
    async (guests) => {
      const xml = buildResponseXml(guests);
      const capture = captureLogger();
      const { service } = makeService(xml, capture.logger);

      const res = await service.search(QUERY, ctx(principal([ROLES.READ])));
      const serialized = JSON.stringify(res);

      // No reveal tokens at all for READ-only, so `token` must be entirely absent now.
      expect(serialized.includes('revealToken')).toBe(false);
      expect(serialized.toLowerCase().includes('token')).toBe(false);
      for (const g of guests) {
        expect(serialized.includes(g.cardToken)).toBe(false);
      }
    },
  );
});
